/*
 * Reproducible vendor extraction: slices the pure geometry builders out of
 * reference/rebel-technical-vehicle.html (studio environment, UI, audio and
 * raycast-inspection code are left behind) and emits
 * game/vehicles/technical.ts exposing assembleTechnical().
 *
 * Run: node scripts/extract-technical.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const html = readFileSync("reference/rebel-technical-vehicle.html", "utf8");
const mod = html.match(/<script type="module">([\s\S]*?)<\/script>/)[1];

const startAnchor = "let materials = {};";
const endAnchor = "function setupEnvironment()";
const start = mod.indexOf(startAnchor);
const end = mod.indexOf(endAnchor);
if (start < 0 || end < 0) throw new Error("technical slice anchors not found");

let body = mod.slice(start, end).trim();
// The vendor mounts to its own scene; the game module returns the group instead.
body = body.replace("scene.add(technicalGroup);", "return technicalGroup;");
if (!body.includes("return technicalGroup;")) {
  throw new Error("assembleVehicle return replacement failed");
}

const header = `/*
 * VENDORED MODULE — generated by scripts/extract-technical.mjs from
 * reference/rebel-technical-vehicle.html. Do not edit by hand; edit the source
 * reference and rerun the extractor. @ts-nocheck: faithful untyped vendor port.
 */
// @ts-nocheck
import * as THREE from "three";

// Shimmed application state (only materialMode is read by the builders).
const state = { materialMode: "tonal" };

// Module-level variables the vendor shares between its builder functions.
let scene, camera, renderer, controls;
let technicalGroup;
let chassisGroup, cabGroup, bedGroup, wheelsGroup, gunGroup;
let turretYawGroup, gunPitchGroup, gunBarrelRecoilGroup, muzzleFlashMesh;
let groundMesh;
let audioCtx = null;
let boxGeometryCount = 0;
let cylinderGeometryCount = 0;
let allModelMeshes = [];
const raycaster = new THREE.Raycaster();
const mouse = new THREE.Vector2();

`;

const footer = `
/* ------------------------------ public API -------------------------------- */
export function assembleTechnical() {
  // Reset per-build audit state so multiple vehicles stay independent.
  boxGeometryCount = 0;
  cylinderGeometryCount = 0;
  allModelMeshes = [];
  initMaterials();
  return assembleVehicle();
}
`;

const out = header + body + "\n" + footer;
mkdirSync("game/vehicles", { recursive: true });
writeFileSync("game/vehicles/technical.ts", out);
console.log(`wrote game/vehicles/technical.ts (${out.split("\n").length} lines)`);
