/*
 * Reproducible vendor extraction: slices the self-contained TankForge factory
 * out of reference/myanmar-mbt-tank.html (the DOM/UI/viewer code is left
 * behind) and emits game/vehicles/tankForge.ts.
 *
 * Run: node scripts/extract-tank.mjs
 * The generated module is committed; rerun only when the vendor file changes.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const html = readFileSync("reference/myanmar-mbt-tank.html", "utf8");
const mod = html.match(/<script type="module">([\s\S]*?)<\/script>/)[1];

// --- Slice A: canvas texture utilities (minus the viewer-only backdrop) ----
const startA = mod.indexOf("function makeCanvas");
const endA = mod.indexOf("/* ------------------------------- LIGHTING");
if (startA < 0 || endA < 0) throw new Error("slice A anchors not found");
let sliceA = mod.slice(startA, endA);
const backdropStart = sliceA.indexOf("function makeBackdrop");
const backdropEnd = sliceA.indexOf("/* Myanmar flag");
if (backdropStart < 0 || backdropEnd < 0) throw new Error("makeBackdrop anchors not found");
sliceA = sliceA.slice(0, backdropStart) + sliceA.slice(backdropEnd);

// --- Slice B: materials, presets and the full geometry factory --------------
const startB = mod.indexOf("const flat =");
const endB = mod.indexOf("/* ============================================================================\n   MOUNT");
if (startB < 0 || endB < 0) throw new Error("slice B anchors not found");
let sliceB = mod.slice(startB, endB);

// Lazy texture singletons: canvas/DOM only exists in browsers, so defer
// texture creation until the factory actually builds a tank (headless tests
// and the VM harness can import geometry helpers without a DOM).
sliceA = sliceA
  .replace(
    "const FLAG_TEX = makeFlagTexture();",
    "let _FLAG_TEX;\nconst FLAG_TEX = () => (_FLAG_TEX ??= makeFlagTexture());"
  )
  .replace(
    "const STAR_TEX = makeStarTexture();",
    "let _STAR_TEX;\nconst STAR_TEX = () => (_STAR_TEX ??= makeStarTexture());"
  );

// Rewrite call sites to invoke the lazy getters.
sliceB = sliceB
  .replaceAll("decal(FLAG_TEX,", "decal(FLAG_TEX(),")
  .replaceAll("decal(STAR_TEX,", "decal(STAR_TEX(),")
  .replaceAll("texture === STAR_TEX", "texture === STAR_TEX()");

const header = `/*
 * VENDORED MODULE — generated by scripts/extract-tank.mjs from
 * reference/myanmar-mbt-tank.html. Do not edit by hand; edit the source
 * reference and rerun the extractor. Kept outside strict type-checking
 * because it is a faithful port of the vendor's untyped factory.
 *
 * Content note (accepted by project owner): faithful integration preserving
 * the vendor's original vehicle names and Myanmar flag/star decal textures.
 */
// @ts-nocheck
import * as THREE from "three";

`;

const footer = `
/* ------------------------------ public API -------------------------------- */
export const TANK_PRESETS = PRESETS;
export { buildTank };
export const TankForge = { build: buildTank, presets: PRESETS };
`;

const out = header + sliceA.trim() + "\n\n" + sliceB.trim() + "\n" + footer;
mkdirSync("game/vehicles", { recursive: true });
writeFileSync("game/vehicles/tankForge.ts", out);
console.log(`wrote game/vehicles/tankForge.ts (${out.split("\n").length} lines)`);
